export function lookupOui(mac: string): { prefix: string; vendor: string | null } | null {
  const hex = mac.toUpperCase().replace(/[^0-9A-F]/g, "");
  if (hex.length < 6) return null;
  const prefix = hex.slice(0, 6);
  return { prefix, vendor: OUI[prefix] ?? null };
}
